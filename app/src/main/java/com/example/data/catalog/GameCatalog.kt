    /** Missions with Session 10 MOS and insertion tags applied (see [tagMission]). */
    val missions: List<MissionTemplate> by lazy {
        // Item 47: every mission and school length follows the global time scale
        (baseMissions + TheaterExpansion.campaignMissions + TheaterExpansion.singleMissions).map { tagMission(it).let { m -> m.copy(durationSeconds = GameTiming.seconds(m.durationSeconds)) } }
    }

    /**
     * Item 32/33 tags, kept in one table. Only missions where a specialty clearly matters get MOS tags.
     * Every field mission can go by ground; most allow helicopters; open terrain allows Airborne drops.
     * HALO and Maritime arrive with Special Forces missions (Session 11).
     */
    private fun withFastRopeSf(ways: List<InsertionMethod>) =
        if (InsertionMethod.HELICOPTER in ways) ways + InsertionMethod.FAST_ROPE else ways

    private fun tagMission(raw: MissionTemplate): MissionTemplate {
        if (raw.scope == MissionScope.TRAINING) return raw
        val m = raw.copy(trainsStats = trainedStatsFor(raw))
        if (m.scope != MissionScope.FIELD_COMBAT) return m
        val A = OperatorSpecialty.ASSAULT
        val R = OperatorSpecialty.RECON
        val S = OperatorSpecialty.SIGNALS
        val B = OperatorSpecialty.BREACHER
        val M = OperatorSpecialty.MEDIC
        val G = InsertionMethod.GROUND
        val H = InsertionMethod.HELICOPTER
        val AB = InsertionMethod.AIRBORNE
        val tags: Map<String, Pair<List<OperatorSpecialty>, List<InsertionMethod>>> = mapOf(
            "msn_ridge_patrol" to (emptyList<OperatorSpecialty>() to listOf(G, H)),
            "msn_relay_sync" to (listOf(S) to listOf(G, H)),
            "msn_harbor_overwatch" to (listOf(R) to listOf(G, H)),
            "msn_convoy_escort" to (emptyList<OperatorSpecialty>() to listOf(G)),
            "msn_citadel_recovery" to (listOf(B, M) to listOf(G, H)),
            "msn_deep_expedition" to (listOf(A, M, S) to listOf(G, H, AB)),
            "msn_sa_timber_cache" to (listOf(R) to listOf(G, H, AB)),
            "msn_sa_medevac_lift" to (listOf(M) to listOf(G, H)),
            "msn_sa_mine_sweep" to (listOf(B) to listOf(G, H)),
            "msn_sa_blackout_raid" to (listOf(S, A) to listOf(G, H, AB)),
            "msn_sa_strait_interdict" to (listOf(A, B) to listOf(G, H)),
            "camp_veridian_1" to (listOf(R) to listOf(G, H, AB)),
            "camp_veridian_2" to (listOf(A) to listOf(G, H)),
            "camp_veridian_3" to (listOf(S, A) to listOf(G, H, AB)),
            "camp_boreal_1" to (listOf(S) to listOf(G, H)),
            "camp_boreal_3" to (emptyList<OperatorSpecialty>() to listOf(G)),
            "camp_boreal_4" to (listOf(B, A) to listOf(G, H)),
            "camp_obsidian_1" to (listOf(R) to listOf(G, H)),
            "camp_obsidian_2" to (listOf(B) to listOf(G, H)),
            "camp_obsidian_3" to (listOf(A, B, M) to listOf(G, H)),
            "camp_kestrel_1" to (listOf(A) to listOf(G, H)),
            "camp_kestrel_3" to (listOf(A, B) to listOf(G, H, AB)),
            "camp_kestrel_4" to (listOf(A, M, S) to listOf(G, H, AB))
        ) + TheaterExpansion.tags
        if (m.requiresSfTeam) {
            // SF teams can go any way they're qualified for; Maritime only on the coast
            val sfWays = listOf(G, H, AB, InsertionMethod.HALO) + if (m.coastal) listOf(InsertionMethod.MARITIME) else emptyList()
            // Item 98: a stage built around one insertion keeps it; the Free Strait needs the full SF squad of 6
            val explicit = m.allowedInsertions != listOf(G) || m.isClandestine
            val freeStrait = m.campaignId == TacticalCalculator.UW_CAMPAIGN_ID
            return m.copy(
                allowedInsertions = if (explicit) m.allowedInsertions else withFastRopeSf(sfWays),
                minOperators = if (freeStrait) TacticalCalculator.SF_MAX_TEAM else TacticalCalculator.SF_MIN_TEAM,
                maxOperators = TacticalCalculator.SF_MAX_TEAM
            )
        }
        // Item 59: wherever a helicopter can land, an Air Assault team can fast-rope in
        fun withFastRope(ways: List<InsertionMethod>) = if (H in ways) ways + InsertionMethod.FAST_ROPE else ways
        if (m.requiredSquads > 1) return m.copy(allowedInsertions = withFastRope(listOf(G, H, AB)))
        val (mos, insertions) = tags[m.id] ?: return m.copy(allowedInsertions = withFastRope(listOf(G, H)))
        return m.copy(recommendedSpecialties = mos, allowedInsertions = withFastRope(insertions))
    }

    /**
     * Item 40: the stats a mission trains, from its focus. Assault and armor: Firepower and Resilience;
     * recon and night stealth: Stealth; signals, EOD and intel: Tech; trauma and rescue: Resilience;
     * diplomatic and staff work: Tech. At most two.
     */
    fun trainedStatsFor(m: MissionTemplate): Set<StatType> {
        if (m.scope == MissionScope.STAFF_DIPLOMATIC) return setOf(StatType.TECH)
        val f = m.primaryFocus.lowercase()
        val picks = linkedSetOf<StatType>()
        if (listOf("stealth", "recon", "infiltration", "night").any { it in f }) picks += StatType.STEALTH
        if (listOf("assault", "armor", "strike", "firepower", "breach", "task force", "valor").any { it in f }) picks += StatType.FIREPOWER
        if (listOf("signals", "tech", "eod", "intel", "ew").any { it in f }) picks += StatType.TECH
        if (listOf("trauma", "rescue", "armor", "escort", "logistics").any { it in f }) picks += StatType.RESILIENCE
        if (picks.isEmpty()) picks += StatType.FIREPOWER
        return picks.take(2).toSet()
    }

